class Reminder(Base, TimestampMixin):
    """A scheduled nudge about an entry.

    Separate from `task.due_at` on purpose: a due date is *when the work is
    owed*, a reminder is *when to be told*. Conflating them means you cannot be
    reminded twice, cannot be reminded the day before, and cannot dismiss the
    reminder without moving the deadline.
    """

    __tablename__ = "reminder"

    id: Mapped[uuid.UUID] = uuid_pk()
    account_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("account.id", ondelete="CASCADE"), nullable=False
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("app_user.id", ondelete="CASCADE"), nullable=False
    )
    entry_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("entry.id", ondelete="CASCADE"))

    remind_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)
    channel: Mapped[str] = mapped_column(
        String(8), default=ReminderChannel.PUSH, server_default="push", nullable=False
    )
    status: Mapped[str] = mapped_column(
        String(12), default=ReminderStatus.SCHEDULED, server_default="scheduled", nullable=False
    )
    # The wording that generated it ("-15m", "la veille à 18h"), kept so the
    # interface can show the rule rather than a bare timestamp.
    offset_rule: Mapped[str | None] = mapped_column(String(32))
    title: Mapped[str | None] = mapped_column(String(200))
    body: Mapped[str | None] = mapped_column(String(500))

    sent_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    attempts: Mapped[int] = mapped_column(
        SmallInteger, default=0, server_default="0", nullable=False
    )
    last_error: Mapped[str | None] = mapped_column(String(120))

    # Makes the dispatcher idempotent: re-running a batch cannot fire the same
    # reminder twice, whatever happens between the send and the status update.
    dedupe_key: Mapped[str] = mapped_column(String(120), nullable=False)

    __table_args__ = (
        _enum_check("channel", ReminderChannel),
        _enum_check("status", ReminderStatus),
        UniqueConstraint("account_id", "dedupe_key", name="reminder_dedupe_unique"),
        Index(
            "reminder_due_idx",
            "remind_at",
            postgresql_where=status == "scheduled",
        ),
        Index("reminder_entry_idx", "entry_id", "remind_at"),
    )


