class Subtask(Base, TimestampMixin):
    """A checklist item under a task.

    Deliberately *not* a nested `entry`. A subtask has no type, no confidence, no
    provenance, no tags — modelling it as an entry would mean every list query in
    the product has to remember to exclude children, and one that forgets shows
    the user their own checklist as top-level noise. One flat level only: two
    levels of nesting is a project, and projects already exist.
    """

