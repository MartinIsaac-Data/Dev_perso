class Device(Base, TimestampMixin):
    __tablename__ = "device"

    id: Mapped[uuid.UUID] = uuid_pk()
    account_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("account.id", ondelete="CASCADE"), nullable=False
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("app_user.id", ondelete="CASCADE"), nullable=False
    )
    # Stable per installation, generated by the client. The natural key for
    # "is this the same device?" — a push token is not, it rotates.
    install_id: Mapped[str] = mapped_column(String(64), nullable=False)
    platform: Mapped[str] = mapped_column(String(16), nullable=False)
    app_version: Mapped[str | None] = mapped_column(String(32))
    os_version: Mapped[str | None] = mapped_column(String(32))
    push_token: Mapped[str | None] = mapped_column(Text)
    # Which service delivers to this device (ADR-038). Stored rather than derived
    # from the platform: an Android phone and a Chrome tab both go through FCM,
    # and a Windows desktop is reachable by WNS or by a local toast depending on
    # how it was installed.
    push_provider: Mapped[str] = mapped_column(
        String(8), default=PushProvider.NONE, server_default="none", nullable=False
    )
    push_token_updated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # Set when the provider tells us the token is dead. Kept rather than deleted
    # so a device that re-registers is recognised instead of duplicated.
    push_failed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    push_failure_count: Mapped[int] = mapped_column(
        SmallInteger, default=0, server_default="0", nullable=False
    )
    name: Mapped[str | None] = mapped_column(String(80))
    last_seen_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    sync_cursor: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    __table_args__ = (
        _enum_check("platform", DevicePlatform),
        _enum_check("push_provider", PushProvider),
        # One row per physical device: re-registering updates the token instead
        # of accumulating rows that all fire for the same phone.
        UniqueConstraint("user_id", "install_id", name="device_install_unique"),
        Index(
            "device_push_idx",
            "account_id",
            "push_provider",
            postgresql_where=revoked_at.is_(None),
        ),
    )


