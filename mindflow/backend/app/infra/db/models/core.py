class Entry(Base, TimestampMixin):
    __tablename__ = "entry"

    id: Mapped[uuid.UUID] = uuid_pk()
    account_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("account.id", ondelete="CASCADE"), nullable=False
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("app_user.id", ondelete="RESTRICT"), nullable=False
    )
    # SET NULL, not CASCADE: deleting the audio must not destroy the tasks drawn
    # from it (ADR-028).
    capture_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("capture.id", ondelete="SET NULL")
    )
    project_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("project.id", ondelete="SET NULL")
    )

    entry_type: Mapped[str] = mapped_column(String(16), nullable=False)
    title: Mapped[str] = mapped_column(String(300), nullable=False)
    body: Mapped[str | None] = mapped_column(Text)
    status: Mapped[str] = mapped_column(
        String(24), default=EntryStatus.ACTIVE, server_default="active", nullable=False
    )

    occurred_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    origin: Mapped[str] = mapped_column(
        String(16), default=EntryOrigin.AI, server_default="ai", nullable=False
    )
    ai_run_id: Mapped[uuid.UUID | None] = mapped_column(PgUUID(as_uuid=True))
    confidence: Mapped[float | None] = mapped_column(Numeric(4, 3))
    source_span_start: Mapped[int | None] = mapped_column(Integer)
    source_span_end: Mapped[int | None] = mapped_column(Integer)

    # Authoritative: a reprocessing run never overwrites a human correction
    # (ADR-027).
    edited_by_user_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # Phase 2. Pinning is a user act, so it is a timestamp rather than a boolean:
    # "pinned, and since when" answers ordering questions a boolean cannot.
    pinned_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # Phase 4. NULL means personal — the phase 1 behaviour, and still the
    # default. Making this mandatory would have forced every existing row into a
    # synthetic "default workspace": a rewrite of working data to satisfy a new
    # abstraction. The restrictive RLS policy of ADR-054 reads this column.
    workspace_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("workspace.id", ondelete="SET NULL")
    )

    # Maintained by PostgreSQL, not by the application (ADR-037). A trigger or an
    # application-side update would drift the moment one write path forgets it,
    # and a search index that is right 95 % of the time is worse than none.
    search_vector: Mapped[str | None] = mapped_column(
        TSVECTOR,
        Computed(
            "setweight(to_tsvector('french', coalesce(title, '')), 'A') || "
            "setweight(to_tsvector('french', coalesce(body, '')), 'B')",
            persisted=True,
        ),
    )

    version: Mapped[int] = mapped_column(Integer, default=1, server_default="1", nullable=False)
    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # `foreign_keys` is required, not decorative: `task` now carries a second FK
    # to `entry` (`recurred_from_entry_id`), and without this the ORM cannot tell
    # which one defines the relationship — it raises rather than guessing, which
    # is the right behaviour and the reason this argument exists.
    task: Mapped[Task | None] = relationship(
        back_populates="entry",
        cascade="all, delete-orphan",
        uselist=False,
        lazy="selectin",
        foreign_keys="Task.entry_id",
    )

    __table_args__ = (
        _enum_check("entry_type", EntryType),
        _enum_check("status", EntryStatus),
        _enum_check("origin", EntryOrigin),
        CheckConstraint(
            "confidence IS NULL OR (confidence >= 0 AND confidence <= 1)",
            name="confidence_range",
        ),
        CheckConstraint(
            "source_span_start IS NULL OR source_span_end > source_span_start",
            name="span_valid",
        ),
        Index(
            "entry_account_occurred_idx",
            "account_id",
            occurred_at.desc(),
            postgresql_where=deleted_at.is_(None),
        ),
        Index(
            "entry_account_type_idx",
            "account_id",
            "entry_type",
            occurred_at.desc(),
            postgresql_where=deleted_at.is_(None),
        ),
        Index(
            "entry_needs_review_idx",
            "account_id",
            "created_at",
            postgresql_where=status == "needs_review",
        ),
        Index("entry_sync_idx", "account_id", "updated_at", "id"),
        Index(
            "entry_search_idx",
            "search_vector",
            postgresql_using="gin",
            postgresql_where=deleted_at.is_(None),
        ),
        Index(
            "entry_pinned_idx",
            "account_id",
            pinned_at.desc(),
            postgresql_where=pinned_at.isnot(None),
        ),
    )


class Task(Base):
    __tablename__ = "task"

    entry_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("entry.id", ondelete="CASCADE"), primary_key=True
    )
    account_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("account.id", ondelete="CASCADE"), nullable=False
    )
    due_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    due_precision: Mapped[str | None] = mapped_column(String(8))
    # The user's own wording, kept so a wrong resolution can be audited.
    due_raw_expression: Mapped[str | None] = mapped_column(String(120))
    priority: Mapped[str] = mapped_column(
        String(8), default=Priority.NORMAL, server_default="normal", nullable=False
    )
    completed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    snoozed_until: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    estimated_minutes: Mapped[int | None] = mapped_column(Integer)
    assignee_label: Mapped[str | None] = mapped_column(String(120))
    recurrence_rule: Mapped[str | None] = mapped_column(String(255))
    # How many occurrences of a recurring task have been completed. Feeds COUNT=
    # so "every Monday, 10 times" actually stops after ten.
    recurrence_count: Mapped[int] = mapped_column(
        Integer, default=0, server_default="0", nullable=False
    )
    # Set on the occurrence generated by completing the previous one, so the
    # timeline can distinguish "you created this" from "it came round again".
    recurred_from_entry_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("entry.id", ondelete="SET NULL")
    )
    # Ordering inside a manual list. Sparse, like subtask.position.
    position: Mapped[int | None] = mapped_column(Integer)
    external_ref: Mapped[dict[str, Any] | None] = mapped_column(JSONB)

    entry: Mapped[Entry] = relationship(back_populates="task", foreign_keys=[entry_id])

    __table_args__ = (
        _enum_check("priority", Priority),
        CheckConstraint(
            "due_precision IS NULL OR due_precision IN ('day','hour','minute')",
            name="due_precision_valid",
        ),
        Index(
            "task_due_idx",
            "due_at",
            postgresql_where=completed_at.is_(None) & due_at.isnot(None),
        ),
    )


